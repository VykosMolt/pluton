// The deck is generated by data/fr/build.py and shared with the web app; copy it into assets at build time.
val dataDir = rootProject.projectDir.parentFile.resolve("public/data/fr")
// Copy, not Sync: Sync would delete the audio/ directory written by syncAudio.
val syncData = tasks.register<Copy>("syncData") {
    from(dataDir) { include("words.json", "forms.json", "story.json", "shelf.json", "conj.json", "grammar.json", "cognates.json") }
    into(layout.buildDirectory.dir("generated/assets/fr"))
    doFirst {
        for (name in listOf("words.json", "conj.json", "grammar.json")) {
            check(dataDir.resolve(name).exists()) {
                "Missing ${dataDir.resolve(name)}; run `uv run data/fr/build.py` first."
            }
        }
    }
}
val storyJson = dataDir.resolve("story.json")
val shelfJson = dataDir.resolve("shelf.json")
// Story + French classic read-along clips: build.py writes [start, end, audioId] for every sentence.
fun audioIdsOf(file: java.io.File, onlyFrench: Boolean): List<String> = runCatching {
    (JsonSlurper().parse(file) as List<*>).flatMap { entry ->
        val map = entry as Map<*, *>
        if (onlyFrench && map["lang"] != "fr") return@flatMap emptyList<String>()
        val sentences = map["sentences"] as? List<*> ?: emptyList<Any?>()
        sentences.mapNotNull { row -> (row as? List<*>)?.getOrNull(2) as? String }
    }.distinct()
}.getOrDefault(emptyList())

val conjJson = dataDir.resolve("conj.json")
// Conjugation cells carry an audio id per person, null where Lexique has no form.
fun conjAudioIdsOf(file: java.io.File): List<String> = runCatching {
    (JsonSlurper().parse(file) as Map<*, *>).values.flatMap { table ->
        val audio = (table as Map<*, *>)["audio"] as? Map<*, *> ?: return@flatMap emptyList<String>()
        audio.values.flatMap { rows -> (rows as? List<*>)?.mapNotNull { it as? String } ?: emptyList() }
    }.distinct()
}.getOrDefault(emptyList())

val audioIds = (
    audioIdsOf(storyJson, onlyFrench = false) +
        audioIdsOf(shelfJson, onlyFrench = true) +
        conjAudioIdsOf(conjJson)
    ).distinct()
val syncAudio = tasks.register<Sync>("syncAudio") {
    from(dataDir.resolve("audio")) { include(audioIds.map { "$it.mp3" }) }
    into(layout.buildDirectory.dir("generated/assets/fr/audio"))
    doFirst {
        check(audioIds.isNotEmpty()) {
            "No read-along sentences found; run `uv run data/fr/build.py` first."
        }
    }
}
tasks.named("preBuild") { dependsOn(syncData, syncAudio) }
tasks.withType<Test>().configureEach { dependsOn(syncData, syncAudio) }

