const number = (x) => (Number.isInteger(x) ? `${x}.0` : `${x}`)
const expectedLine = (c) =>
    `Expected(${c.due.getTime()}L, ${number(c.stability)}, ${number(c.difficulty)}, ${c.elapsed_days}, ` +
    `${c.scheduled_days}, ${c.reps}, ${c.lapses}, ${c.learning_steps}, State.${STATE[c.state]}, ` +
    `${c.last_review ? `${c.last_review.getTime()}L` : 'null'})`

