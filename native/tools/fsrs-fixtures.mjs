const D = 86_400_000
const R = { Again: Rating.Again, Hard: Rating.Hard, Good: Rating.Good, Easy: Rating.Easy }
const STATE = ['New', 'Learning', 'Review', 'Relearning']
const f = fsrs({ enable_fuzz: false })

